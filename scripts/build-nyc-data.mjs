// Builds the runtime data for /nyc from the raw sources in data/nyc/source.
//
//   node scripts/build-nyc-data.mjs
//
// Sources:
//   - NYC Planning 2020 Neighborhood Tabulation Areas, filtered to residential
//     areas: https://data.cityofnewyork.us/d/9nt8-h7nd
//   - MTA subway lines: https://data.ny.gov/d/s692-irgq
//
// Outputs:
//   - public/nyc/data/neighborhoods.<hash>.geojson  simplified polygons
//   - public/nyc/data/subway-lines.<hash>.geojson   simplified lines
//   - lib/nyc/generated/data-manifest.ts            URLs for the files above
//   - lib/nyc/generated/neighborhoods.ts            static list + bounds
//   - lib/nyc/generated/og-paths.ts                 SVG paths for the OG image
//
// The share-link format depends on lib/nyc/url-ids.json. This script refuses
// to run if the neighborhood IDs no longer match the current version there, so
// data changes can't silently break links people have already shared.

import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import mapshaper from "mapshaper";
import { displayNameFor } from "./nyc-display-names.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "data", "nyc", "source");
const publicDir = path.join(root, "public", "nyc", "data");
const generatedDir = path.join(root, "lib", "nyc", "generated");

const NEIGHBORHOOD_SIMPLIFY = "15%";
const SUBWAY_SIMPLIFY = "5%";
const OG_SIMPLIFY = "4%";
const OG_WIDTH = 1200;
const OG_HEIGHT = 630;
const OG_PADDING = 36;
// Room on the left for the stats card drawn by app/nyc/og/route.tsx.
const OG_CARD_INSET = 300;

const BOROUGHS = ["Manhattan", "Brooklyn", "Queens", "Bronx", "Staten Island"];

async function simplify(geojson, amount, extraCommands = "") {
  const output = await mapshaper.applyCommands(
    `-i input.geojson -simplify ${amount} weighted keep-shapes ${extraCommands} -o output.geojson precision=0.00001`,
    { "input.geojson": JSON.stringify(geojson) },
  );
  return JSON.parse(output["output.geojson"].toString());
}

function hashOf(contents) {
  return createHash("sha1").update(contents).digest("hex").slice(0, 8);
}

function eachRing(geometry, visit) {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) visit(ring);
  }
}

function bboxOf(geometry) {
  const bbox = [Infinity, Infinity, -Infinity, -Infinity];
  eachRing(geometry, (ring) => {
    for (const [x, y] of ring) {
      bbox[0] = Math.min(bbox[0], x);
      bbox[1] = Math.min(bbox[1], y);
      bbox[2] = Math.max(bbox[2], x);
      bbox[3] = Math.max(bbox[3], y);
    }
  });
  return bbox.map((value) => Number(value.toFixed(5)));
}

function unionBbox(bboxes) {
  return bboxes.reduce(
    (union, bbox) => [
      Math.min(union[0], bbox[0]),
      Math.min(union[1], bbox[1]),
      Math.max(union[2], bbox[2]),
      Math.max(union[3], bbox[3]),
    ],
    [Infinity, Infinity, -Infinity, -Infinity],
  );
}

// Web Mercator, fitted to the OG canvas.
function makeProjection(bbox) {
  // Both axes in radians so the aspect ratio is right.
  const mercX = (lng) => (lng * Math.PI) / 180;
  const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  const west = mercX(bbox[0]);
  const east = mercX(bbox[2]);
  const south = mercY(bbox[1]);
  const north = mercY(bbox[3]);
  const scale = Math.min(
    (OG_WIDTH - OG_CARD_INSET - OG_PADDING * 2) / (east - west),
    (OG_HEIGHT - OG_PADDING * 2) / (north - south),
  );
  const offsetX =
    OG_CARD_INSET + (OG_WIDTH - OG_CARD_INSET - (east - west) * scale) / 2;
  const offsetY = (OG_HEIGHT - (north - south) * scale) / 2;
  return ([lng, lat]) => [
    ((mercX(lng) - west) * scale + offsetX).toFixed(1),
    ((north - mercY(lat)) * scale + offsetY).toFixed(1),
  ];
}

function svgPath(geometry, project) {
  const parts = [];
  eachRing(geometry, (ring) => {
    parts.push(
      ring
        .map((point, index) => `${index === 0 ? "M" : "L"}${project(point).join(",")}`)
        .join("") + "Z",
    );
  });
  return parts.join("");
}

function tsHeader() {
  return "// Generated by scripts/build-nyc-data.mjs. Do not edit by hand.\n\n";
}

async function main() {
  const [neighborhoodsRaw, subwayRaw, urlIds] = await Promise.all([
    readFile(path.join(sourceDir, "nyc-neighborhoods.geojson"), "utf8").then(
      JSON.parse,
    ),
    readFile(path.join(sourceDir, "nyc-subway-lines.geojson"), "utf8").then(
      JSON.parse,
    ),
    readFile(path.join(root, "lib", "nyc", "url-ids.json"), "utf8").then(
      JSON.parse,
    ),
  ]);

  // Guard the share-link format.
  const sourceIds = neighborhoodsRaw.features
    .map((feature) => feature.properties.id)
    .sort();
  const frozenIds = urlIds.versions[urlIds.current];
  if (JSON.stringify(sourceIds) !== JSON.stringify(frozenIds)) {
    throw new Error(
      `Neighborhood IDs differ from lib/nyc/url-ids.json version ${urlIds.current}. ` +
        "Add a new version there (keep the old one so existing links still decode) before rebuilding.",
    );
  }

  // One interior point per neighborhood for labels. Polygon labels would
  // repeat on every part of a multipolygon (piers, islands).
  const labelPoints = await mapshaper
    .applyCommands("-i input.geojson -points inner -o output.geojson", {
      "input.geojson": JSON.stringify(neighborhoodsRaw),
    })
    .then((output) => JSON.parse(output["output.geojson"].toString()));
  const labelById = new Map(
    labelPoints.features.map((feature) => [
      feature.properties.id,
      feature.geometry.coordinates.map((value) => Number(value.toFixed(5))),
    ]),
  );

  // Neighborhood list with display names.
  const neighborhoods = neighborhoodsRaw.features
    .map(({ properties, geometry }) => {
      const { name, includes } = displayNameFor(properties.name);
      return {
        id: properties.id,
        name,
        includes,
        ntaName: properties.name,
        borough: properties.borough,
        bbox: bboxOf(geometry),
        label: labelById.get(properties.id),
      };
    })
    .sort(
      (a, b) =>
        BOROUGHS.indexOf(a.borough) - BOROUGHS.indexOf(b.borough) ||
        a.name.localeCompare(b.name),
    );

  const seen = new Set();
  for (const { name, borough } of neighborhoods) {
    const key = `${borough}:${name}`;
    if (seen.has(key)) {
      throw new Error(`Duplicate display name in ${borough}: ${name}`);
    }
    seen.add(key);
  }

  const nycBounds = unionBbox(neighborhoods.map(({ bbox }) => bbox));
  const boroughBounds = Object.fromEntries(
    BOROUGHS.map((borough) => [
      borough,
      unionBbox(
        neighborhoods
          .filter((item) => item.borough === borough)
          .map(({ bbox }) => bbox),
      ),
    ]),
  );

  // Runtime GeoJSON: simplified, with only the properties the map needs.
  const nameById = new Map(neighborhoods.map((item) => [item.id, item.name]));
  const neighborhoodsSimplified = await simplify(
    neighborhoodsRaw,
    NEIGHBORHOOD_SIMPLIFY,
  );
  neighborhoodsSimplified.features = neighborhoodsSimplified.features.map(
    (feature) => ({
      type: "Feature",
      properties: {
        id: feature.properties.id,
        name: nameById.get(feature.properties.id),
        borough: feature.properties.borough,
      },
      geometry: feature.geometry,
    }),
  );

  const subwaySimplified = await simplify(subwayRaw, SUBWAY_SIMPLIFY);
  subwaySimplified.features = subwaySimplified.features.map((feature) => ({
    type: "Feature",
    properties: {
      id: feature.properties.id,
      service: feature.properties.service,
      name: feature.properties.name,
      color: feature.properties.color,
    },
    geometry: feature.geometry,
  }));

  // OG image paths, simplified harder and projected onto the canvas.
  const ogSimplified = await simplify(neighborhoodsRaw, OG_SIMPLIFY);
  const project = makeProjection(nycBounds);
  const ogPaths = Object.fromEntries(
    ogSimplified.features.map((feature) => [
      feature.properties.id,
      svgPath(feature.geometry, project),
    ]),
  );

  // Write outputs.
  await mkdir(publicDir, { recursive: true });
  await mkdir(generatedDir, { recursive: true });
  for (const stale of await readdir(publicDir)) {
    if (stale.endsWith(".geojson")) await rm(path.join(publicDir, stale));
  }

  const neighborhoodsJson = JSON.stringify(neighborhoodsSimplified);
  const subwayJson = JSON.stringify(subwaySimplified);
  const neighborhoodsFile = `neighborhoods.${hashOf(neighborhoodsJson)}.geojson`;
  const subwayFile = `subway-lines.${hashOf(subwayJson)}.geojson`;
  await writeFile(path.join(publicDir, neighborhoodsFile), neighborhoodsJson);
  await writeFile(path.join(publicDir, subwayFile), subwayJson);

  await writeFile(
    path.join(generatedDir, "data-manifest.ts"),
    tsHeader() +
      `export const NEIGHBORHOODS_GEOJSON_URL = "/nyc/data/${neighborhoodsFile}";\n` +
      `export const SUBWAY_GEOJSON_URL = "/nyc/data/${subwayFile}";\n`,
  );

  await writeFile(
    path.join(generatedDir, "neighborhoods.ts"),
    tsHeader() +
      `import type { Borough, Bounds, Neighborhood } from "../types";\n\n` +
      `export const NYC_BOUNDS: Bounds = ${JSON.stringify(nycBounds)};\n\n` +
      `export const BOROUGH_BOUNDS: Record<Borough, Bounds> = ${JSON.stringify(
        boroughBounds,
        null,
        2,
      )};\n\n` +
      `export const NEIGHBORHOODS: readonly Neighborhood[] = ${JSON.stringify(
        neighborhoods,
        null,
        2,
      )};\n`,
  );

  await writeFile(
    path.join(generatedDir, "og-paths.ts"),
    tsHeader() +
      `export const OG_WIDTH = ${OG_WIDTH};\n` +
      `export const OG_HEIGHT = ${OG_HEIGHT};\n\n` +
      `export const OG_PATHS: Record<string, string> = ${JSON.stringify(
        ogPaths,
        null,
        1,
      )};\n`,
  );

  const kb = (text) => `${Math.round(Buffer.byteLength(text) / 1024)} KB`;
  console.log(`neighborhoods: ${neighborhoodsFile} (${kb(neighborhoodsJson)})`);
  console.log(`subway lines:  ${subwayFile} (${kb(subwayJson)})`);
  console.log(
    `og paths:      ${kb(JSON.stringify(ogPaths))} across ${
      Object.keys(ogPaths).length
    } neighborhoods`,
  );
}

await main();
